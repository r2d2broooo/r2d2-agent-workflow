from .secret_redaction import redact_secrets

DB_PATH = os.path.join(os.path.dirname(__file__), "..", "chat_log.db")
_SECRETS_SCRUBBED = False

_REPORT_SOURCE_LABELS = {
    "claude_bot": "Claude",
    "codex_bot": "Codex",
    "llm_bot": "Local LLM",
    "dashboard": "Dashboard",
}
_REPORT_REQUEST_RE = re.compile(
    r"\b(?:report|analysis|analy[sz]e|review|audit|summary|summari[sz]e|feedback)\b",
    re.IGNORECASE,
)
_WORK_REPORT_RE = re.compile(
    r"(?:^|\n)\s*(?:#+\s*)?(?:work\s+report|daily\s+report|monthly\s+report|"
    r"report\s*(?:summary|findings|status)?\s*:)",
    re.IGNORECASE,
)
_REPORT_FAILURE_RE = re.compile(
    r"(?:encountered an error|runner failed|analysis failed|traceback \(most recent call last\)|"
    r"exit code \d+|command not found)",
    re.IGNORECASE,
)


def _scrub_existing_secrets(conn: sqlite3.Connection) -> None:
    """Redact credential-shaped text already stored in the shared database."""
    global _SECRETS_SCRUBBED
    if _SECRETS_SCRUBBED:
        return
    for table, column in (("messages", "text"), ("reports", "analysis"),
                          ("monthly_report_reviews", "analysis"),
                          ("monthly_report_reviews", "operator_feedback"),
                          ("predictions", "raw_text"), ("predictions", "reasoning"),
                          ("predictions", "outcome_note")):
        rows = conn.execute(f"SELECT rowid, {column} FROM {table} WHERE {column} IS NOT NULL").fetchall()
        updates = [(redact_secrets(value), row_id) for row_id, value in rows
                   if redact_secrets(value) != value]
        if updates:
            conn.executemany(f"UPDATE {table} SET {column} = ? WHERE rowid = ?", updates)
    conn.commit()
    _SECRETS_SCRUBBED = True


def _connect() -> sqlite3.Connection:
    conn = sqlite3.connect(DB_PATH)
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS messages (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            chat_id INTEGER NOT NULL,
            chat_title TEXT,
            bot_name TEXT NOT NULL,
            role TEXT NOT NULL,
            text TEXT NOT NULL,
            ts REAL NOT NULL
        )
        """
    )
    conn.execute("CREATE INDEX IF NOT EXISTS idx_messages_chat_id ON messages(chat_id)")
    # images: JSON list of chart/image file paths attached to a message (charts
    # generated by the analysis router). Added so the dashboard chats can show
    # charts like the telegram bots do.
    try:
        conn.execute("ALTER TABLE messages ADD COLUMN images TEXT")
    except sqlite3.OperationalError:
        pass
    # One Telegram event reaches several independent bot processes. Key it by its
    # source identity, not text/time, so genuine repeated messages remain distinct.
    try:
        conn.execute("ALTER TABLE messages ADD COLUMN source_key TEXT NOT NULL DEFAULT ''")
    except sqlite3.OperationalError:
        pass
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_messages_source_key "
        "ON messages(source_key) WHERE source_key != ''"
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS reports (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            chat_id INTEGER,
            label TEXT,
            image_path TEXT NOT NULL,
            url TEXT,
            analysis TEXT,
            ts REAL NOT NULL,
            source TEXT NOT NULL DEFAULT '',
            report_type TEXT NOT NULL DEFAULT 'report',
            dedupe_key TEXT NOT NULL DEFAULT ''
        )
        """
    )
    try:
        conn.execute("ALTER TABLE reports ADD COLUMN archived INTEGER NOT NULL DEFAULT 0")
    except sqlite3.OperationalError:
        pass
    for column, decl in (
        ("source", "TEXT NOT NULL DEFAULT ''"),
        ("report_type", "TEXT NOT NULL DEFAULT 'report'"),
        ("dedupe_key", "TEXT NOT NULL DEFAULT ''"),
    ):
        try:
            conn.execute(f"ALTER TABLE reports ADD COLUMN {column} {decl}")
        except sqlite3.OperationalError:
            pass
    conn.execute(
        "CREATE UNIQUE INDEX IF NOT EXISTS idx_reports_dedupe_key "
        "ON reports(dedupe_key) WHERE dedupe_key != ''"
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS monthly_report_reviews (
            month TEXT PRIMARY KEY,
            report_count INTEGER NOT NULL DEFAULT 0,
            report_ids TEXT NOT NULL DEFAULT '[]',
            source_counts TEXT NOT NULL DEFAULT '{}',
            type_counts TEXT NOT NULL DEFAULT '{}',
            analysis TEXT NOT NULL DEFAULT '',
            operator_feedback TEXT NOT NULL DEFAULT '',
            model TEXT NOT NULL DEFAULT '',
            created_ts REAL NOT NULL,
            updated_ts REAL NOT NULL
        )
        """
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS tasks (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'todo',
            owner TEXT,
            deadline TEXT,
            notes TEXT,
            created_ts REAL NOT NULL,
            updated_ts REAL NOT NULL
        )
        """
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS notes (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            content TEXT NOT NULL DEFAULT '',
            created_ts REAL NOT NULL,
            updated_ts REAL NOT NULL
        )
        """
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS events (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            title TEXT NOT NULL,
            date TEXT NOT NULL,
            notes TEXT,
            created_ts REAL NOT NULL
        )
        """
    )
    try:
        conn.execute("ALTER TABLE notes ADD COLUMN color TEXT NOT NULL DEFAULT ''")
    except sqlite3.OperationalError:
        pass
    try:
        conn.execute("ALTER TABLE notes ADD COLUMN pinned INTEGER NOT NULL DEFAULT 0")
    except sqlite3.OperationalError:
        pass
    try:
        conn.execute("ALTER TABLE notes ADD COLUMN label TEXT NOT NULL DEFAULT ''")
    except sqlite3.OperationalError:
        pass
    # The Idea Map was removed 2026-10-28 (operator); its rows are archived in
    # research_archive/idea_map_2026-10-28/idea_map.json and its tables dropped.
    # Retired 2026-08-27 with the Backtest tab. The table and its existing rows are kept
    # read-only as history; nothing in the live path writes to or reads from it any more.
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS backtests (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            ticker TEXT NOT NULL,
            setup TEXT NOT NULL,
            strategy TEXT NOT NULL DEFAULT '',
            period TEXT NOT NULL DEFAULT '2y',
            hold_days INTEGER NOT NULL DEFAULT 10,
            rr_target REAL NOT NULL DEFAULT 3.0,
            result TEXT NOT NULL DEFAULT '',
            chart_path TEXT NOT NULL DEFAULT '',
            created_ts REAL NOT NULL
        )
        """
    )
    for col, decl in (("model", "TEXT NOT NULL DEFAULT ''"),
                      ("analysis", "TEXT NOT NULL DEFAULT ''")):
        try:
            conn.execute(f"ALTER TABLE backtests ADD COLUMN {col} {decl}")
        except sqlite3.OperationalError:
            pass

    # Predictions: every analysis an agent makes is logged here, then graded
    # against real future price action so each model builds a track record it
    # can learn from (right/wrong calls). Shared by dashboard + Telegram.
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS predictions (
            id INTEGER PRIMARY KEY AUTOINCREMENT,
            created_ts REAL NOT NULL,
            source TEXT NOT NULL DEFAULT 'dashboard',
            model TEXT NOT NULL,
            ticker TEXT NOT NULL,
            analysis_type TEXT NOT NULL DEFAULT 'chart',
            timeframes TEXT NOT NULL DEFAULT '',
            rating TEXT NOT NULL DEFAULT '',
            conviction TEXT NOT NULL DEFAULT '',
            entry_price REAL,
            target1_price REAL,
            target1_days INTEGER,
            target2_price REAL,
            target2_days INTEGER,
            invalidation REAL,
            support REAL,
            resistance REAL,
            reasoning TEXT NOT NULL DEFAULT '',
            raw_text TEXT NOT NULL DEFAULT '',
            chart_paths TEXT NOT NULL DEFAULT '',
            status TEXT NOT NULL DEFAULT 'open',
            graded_ts REAL,
            price_at_grade REAL,
            result_label TEXT NOT NULL DEFAULT '',
            score REAL,
            outcome_note TEXT NOT NULL DEFAULT ''
        )
        """
    )
    # probability: the model's own estimated chance (0-100) the primary target is
    # reached before invalidation. Added later, so migrate existing DBs in place.
    try:
        conn.execute("ALTER TABLE predictions ADD COLUMN probability REAL")
    except sqlite3.OperationalError:
        pass
    _scrub_existing_secrets(conn)
    return conn


def log_message(chat_id: int, chat_title: str, bot_name: str, role: str, text: str,
                images: list[str] | None = None, *, source_key: str = "") -> int:
    """Store a chat message and preserve report-shaped agent output in Reports.

    The dashboard has historically kept image-backed ticker analyses only. A
    completion report or written review is still a report even when it has no
    image, so qualified agent replies are copied into the report ledger here.
    The message id is the idempotency key, which prevents a websocket replay
    from creating a duplicate card.
    """
    conn = _connect()
    try:
        images_json = json.dumps(images) if images else None
        clean_text = redact_secrets(text)
        cur = conn.execute(
            "INSERT INTO messages (chat_id, chat_title, bot_name, role, text, ts, images, source_key) "
            "VALUES (?, ?, ?, ?, ?, ?, ?, ?) "
            "ON CONFLICT(source_key) WHERE source_key != '' DO NOTHING",
            (chat_id, chat_title, bot_name, role, clean_text, time.time(), images_json, source_key),
        )
        if not cur.rowcount:
            message_id = conn.execute(
                "SELECT id FROM messages WHERE source_key = ?", (source_key,)
            ).fetchone()[0]
            conn.commit()
            return int(message_id)
        message_id = int(cur.lastrowid)
        if role == "assistant":
            _auto_capture_agent_report(conn, chat_id, bot_name, clean_text, message_id)
        conn.commit()
        return message_id
    finally:
        conn.close()


def get_chats() -> list[dict]:
    conn = _connect()
    try:
        rows = conn.execute(
            """
            SELECT chat_id,
                   COALESCE(MAX(chat_title), '') AS chat_title,
                   GROUP_CONCAT(DISTINCT bot_name) AS bots,
                   MAX(ts) AS last_ts,
                   COUNT(*) AS message_count
            FROM messages
            GROUP BY chat_id
            ORDER BY last_ts DESC
            """
        ).fetchall()
        return [
            {
                "chat_id": r[0],
                "chat_title": r[1] or str(r[0]),
                "bots": r[2],
                "last_ts": r[3],
                "message_count": r[4],
            }
            for r in rows
        ]
    finally:
        conn.close()


def get_recent_messages(chat_id: int, limit: int = 500) -> list[dict]:
    """Return up to `limit` most recent messages for a chat, oldest first."""
    conn = _connect()
    try:
        rows = conn.execute(
            """
            SELECT id, chat_id, chat_title, bot_name, role, text, ts
            FROM messages
            WHERE chat_id = ?
            ORDER BY id DESC
            LIMIT ?
            """,
            (chat_id, limit),
        ).fetchall()
        rows.reverse()
        return [
            {
                "id": r[0],
                "chat_id": r[1],
                "chat_title": r[2],
                "bot_name": r[3],
                "role": r[4],
                "text": r[5],
                "ts": r[6],
            }
            for r in rows
        ]
    finally:
        conn.close()


def report_source_label(source: str | None) -> str:
    """Human-readable source name used consistently by Reports and reviews."""
    source = (source or "").strip()
    return _REPORT_SOURCE_LABELS.get(source, source.replace("_bot", "").replace("_", " ").title() or "Stored report")


def _report_title(bot_name: str, request_text: str | None) -> str:
    source = report_source_label(bot_name)
    subject = " ".join((request_text or "").strip().split())
    subject = re.sub(r"^@(?:1|2|3|claude|codex|llm)\b\s*", "", subject, flags=re.IGNORECASE)
    if subject:
        return f"{source} report — {subject[:96]}"
    return f"{source} report"


def _auto_capture_agent_report(conn: sqlite3.Connection, chat_id: int, bot_name: str,
                               text: str, message_id: int) -> None:
    """Copy substantive agent reports into ``reports`` without duplicating errors.

    A reply qualifies when it uses an explicit report heading, completes a
    report-oriented request, or reads like a work hand-off (completed +
    evidence). Short acknowledgements and provider failures stay in chat only.
    """
    if bot_name not in _REPORT_SOURCE_LABELS or len((text or "").strip()) < 80:
        return
    # @2 stock analyses are stored by llm_views under report_type "local_analysis"; don't duplicate.
    if bot_name == "llm_bot" and re.match(r"^[A-Z][A-Z0-9.\-]{0,9} — analysis", (text or "").strip()):
        return
    if _REPORT_FAILURE_RE.search(text or ""):
        return
    row = conn.execute(
        "SELECT text FROM messages WHERE chat_id = ? AND role = 'user' ORDER BY id DESC LIMIT 1",
        (chat_id,),
    ).fetchone()
    request_text = row[0] if row else ""
    low = (text or "").lower()
    looks_like_handoff = (
        len(text) >= 160
        and any(marker in low for marker in ("done", "completed", "implemented", "verified", "tested", "results"))
        and any(marker in low for marker in ("test", "check", "changed", "saved", "built", "result", "verified"))
    )
    if not (_WORK_REPORT_RE.search(text or "") or _REPORT_REQUEST_RE.search(request_text or "") or looks_like_handoff):
        return
    report_type = "analysis" if re.search(r"\b(?:analysis|analy[sz]e)\b", request_text or "", re.I) else "work"
    now = time.time()
    conn.execute(
        """
        INSERT INTO reports (chat_id, label, image_path, url, analysis, ts, source, report_type, dedupe_key)
        VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
        ON CONFLICT(dedupe_key) WHERE dedupe_key != '' DO UPDATE SET
            analysis = excluded.analysis, ts = excluded.ts, source = excluded.source,
            report_type = excluded.report_type, archived = 0
        """,
        (chat_id, _report_title(bot_name, request_text), "", None, text, now,
         report_source_label(bot_name), report_type, f"message:{message_id}"),
    )


def add_report(chat_id: int | None, label: str, image_path: str = "", url: str | None = None,
               analysis: str = "", *, source: str = "", report_type: str = "report",
               dedupe_key: str | None = None, ts: float | None = None) -> int:
    """Persist an image or text report. ``dedupe_key`` turns repeat saves into updates."""
    conn = _connect()
    try:
        clean_source = report_source_label(source)
        clean_type = (report_type or "report").strip().lower()[:48] or "report"
        clean_key = (dedupe_key or "").strip()[:240]
        params = (
            chat_id, (label or "Stored report").strip()[:240], image_path or "", url,
            redact_secrets(analysis or ""), float(ts if ts is not None else time.time()),
            clean_source, clean_type, clean_key,
        )
        cur = conn.execute(
            """
            INSERT INTO reports (chat_id, label, image_path, url, analysis, ts, source, report_type, dedupe_key)
            VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?)
            ON CONFLICT(dedupe_key) WHERE dedupe_key != '' DO UPDATE SET
                chat_id = excluded.chat_id, label = excluded.label, image_path = excluded.image_path,
                url = excluded.url, analysis = excluded.analysis, ts = excluded.ts,
                source = excluded.source, report_type = excluded.report_type, archived = 0
            """,
            params,
        )
        conn.commit()
        if clean_key:
            row = conn.execute("SELECT id FROM reports WHERE dedupe_key = ?", (clean_key,)).fetchone()
            return int(row[0]) if row else 0
        return int(cur.lastrowid or 0)
    finally:
        conn.close()


