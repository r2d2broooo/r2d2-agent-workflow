_PREDICTION_COLS = (
    "id, created_ts, source, model, ticker, analysis_type, timeframes, rating, "
    "conviction, entry_price, target1_price, target1_days, target2_price, "
    "target2_days, invalidation, support, resistance, reasoning, raw_text, "
    "chart_paths, status, graded_ts, price_at_grade, result_label, score, outcome_note, "
    "probability"
)


def _prediction_row(r) -> dict:
    keys = [c.strip() for c in _PREDICTION_COLS.split(",")]
    d = dict(zip(keys, r))
    d["chart_paths"] = [p for p in (d.get("chart_paths") or "").split("|") if p]
    return d


def add_prediction(model: str, ticker: str, **fields) -> int:
    cols = {
        "source": "dashboard", "analysis_type": "chart", "timeframes": "",
        "rating": "", "conviction": "", "entry_price": None,
        "target1_price": None, "target1_days": None, "target2_price": None,
        "target2_days": None, "invalidation": None, "support": None,
        "resistance": None, "reasoning": "", "raw_text": "", "chart_paths": "",
        "status": "open", "probability": None, "outcome_note": "",
    }
    cols.update({k: v for k, v in fields.items() if k in cols})
    if isinstance(cols["chart_paths"], (list, tuple)):
        cols["chart_paths"] = "|".join(cols["chart_paths"])
    for field in ("reasoning", "raw_text", "outcome_note"):
        cols[field] = redact_secrets(cols.get(field, ""))
    conn = _connect()
    try:
        names = ["created_ts", "model", "ticker"] + list(cols)
        placeholders = ", ".join("?" for _ in names)
        values = [time.time(), model, ticker] + list(cols.values())
        cur = conn.execute(
            f"INSERT INTO predictions ({', '.join(names)}) VALUES ({placeholders})",
            values,
        )
        conn.commit()
        return cur.lastrowid
    finally:
        conn.close()


def get_predictions(limit: int = 200, model: str | None = None,
                    status: str | None = None) -> list[dict]:
    conn = _connect()
    try:
        where, params = [], []
        if model:
            where.append("model = ?"); params.append(model)
        if status:
            where.append("status = ?"); params.append(status)
        clause = ("WHERE " + " AND ".join(where)) if where else ""
        rows = conn.execute(
            f"SELECT {_PREDICTION_COLS} FROM predictions {clause} "
            f"ORDER BY id DESC LIMIT ?",
            (*params, limit),
        ).fetchall()
        return [_prediction_row(r) for r in rows]
    finally:
        conn.close()


